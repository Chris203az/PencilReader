import CoreGraphics
import Foundation
import Testing
@testable import ReaderCore

/// Builds lines with evenly spaced word boxes (normalized coordinates).
private func makeLines(_ texts: [String], lineHeight: CGFloat = 0.02, gap: CGFloat = 0.008) -> [RawLine] {
    texts.enumerated().map { i, text in
        let y = 0.1 + CGFloat(i) * (lineHeight + gap)
        let tokens = text.split(separator: " ").map(String.init)
        let words = tokens.enumerated().map { j, t in
            RawWord(text: t, rect: CGRect(x: 0.1 + CGFloat(j) * 0.08, y: y, width: 0.07, height: lineHeight))
        }
        return RawLine(text: text, rect: CGRect(x: 0.1, y: y, width: 0.8, height: lineHeight), words: words)
    }
}

struct PageTextTests {
    @Test func rejoinsHyphenatedWord() {
        let page = PageText(lines: makeLines(["The aero-", "dynamic force"]))
        #expect(page.blocks.count == 1)
        #expect(page.blocks[0].text == "The aerodynamic force")
        #expect(page.text(for: [1, 2]) == "aerodynamic")
    }

    @Test func trimsPunctuation() {
        let page = PageText(lines: makeLines(["entered a stall, when"]))
        #expect(page.text(for: [2]) == "stall")
        #expect(page.text(for: [1, 2]) == "a stall")
    }

    @Test func keepsInnerHyphen() {
        let page = PageText(lines: makeLines(["the trailing-edge flap"]))
        #expect(page.text(for: [1]) == "trailing-edge")
    }

    @Test func contextIsTheContainingSentence() {
        let page = PageText(lines: makeLines([
            "Lift is generated by the wing. The aircraft",
            "entered a stall when the angle of attack",
            "exceeded the critical value. Recovery followed."
        ]))
        let stall = page.words.first { $0.text == "stall" }!.id
        let context = page.contextSentences(for: [stall])!
        #expect(context.text == "The aircraft entered a stall when the angle of attack exceeded the critical value.")
        #expect(context.text[context.selection!] == "stall")
    }

    @Test func contextSelectionExcludesPunctuation() {
        let page = PageText(lines: makeLines(["It is called the angle of attack."]))
        let context = page.contextSentences(for: [4, 5, 6])!
        #expect(context.text[context.selection!] == "angle of attack")
    }

    @Test func contextSpansSentencesOfMultiWordSelection() {
        let page = PageText(lines: makeLines(["One two. Three four."]))
        #expect(page.contextSentences(for: [1, 2])?.text == "One two. Three four.")
    }

    @Test func largeGapStartsNewBlock() {
        var lines = makeLines(["First paragraph line", "second line"])
        lines += makeLines(["Next paragraph"]).map {
            var l = $0
            l.rect.origin.y += 0.1
            l.words = l.words.map { RawWord(text: $0.text, rect: $0.rect.offsetBy(dx: 0, dy: 0.1)) }
            return l
        }
        let page = PageText(lines: lines)
        #expect(page.blocks.count == 2)
        #expect(page.blocks[1].text == "Next paragraph")
    }

    @Test func rawLinesRoundTripThroughJSON() throws {
        let page = PageText(lines: makeLines(["The aero-", "dynamic force"]))
        let data = try JSONEncoder().encode(page.rawLines)
        let restored = PageText(lines: try JSONDecoder().decode([RawLine].self, from: data))
        #expect(restored.rawLines == page.rawLines)
        #expect(restored.blocks == page.blocks)
    }
}
