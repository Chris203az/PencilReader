package it.pencilreader.core

import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.json.Json
import org.junit.Test

class PageTextTest {
    @Test fun rejoinsHyphenatedWord() {
        val page = PageText(makeLines(listOf("The aero-", "dynamic force")))
        expect(page.blocks.size == 1)
        expect(page.blocks[0].text == "The aerodynamic force")
        expect(page.text(listOf(1, 2)) == "aerodynamic")
    }

    @Test fun trimsPunctuation() {
        val page = PageText(makeLines(listOf("entered a stall, when")))
        expect(page.text(listOf(2)) == "stall")
        expect(page.text(listOf(1, 2)) == "a stall")
    }

    @Test fun keepsInnerHyphen() {
        val page = PageText(makeLines(listOf("the trailing-edge flap")))
        expect(page.text(listOf(1)) == "trailing-edge")
    }

    @Test fun contextIsTheContainingSentence() {
        val page = PageText(makeLines(listOf(
            "Lift is generated by the wing. The aircraft",
            "entered a stall when the angle of attack",
            "exceeded the critical value. Recovery followed.",
        )))
        val stall = page.words.first { it.text == "stall" }.id
        val context = page.contextSentences(listOf(stall))!!
        expect(context.text == "The aircraft entered a stall when the angle of attack exceeded the critical value.", context.text)
        expect(context.selection!!.of(context.text) == "stall")
    }

    @Test fun contextSelectionExcludesPunctuation() {
        val page = PageText(makeLines(listOf("It is called the angle of attack.")))
        val context = page.contextSentences(listOf(4, 5, 6))!!
        expect(context.selection!!.of(context.text) == "angle of attack")
    }

    @Test fun contextSpansSentencesOfMultiWordSelection() {
        val page = PageText(makeLines(listOf("One two. Three four.")))
        expect(page.contextSentences(listOf(1, 2))?.text == "One two. Three four.")
    }

    @Test fun largeGapStartsNewBlock() {
        val lines = makeLines(listOf("First paragraph line", "second line")) +
            makeLines(listOf("Next paragraph")).map { l ->
                RawLine(l.text, l.rect.offsetBy(0.0, 0.1), l.words.map { RawWord(it.text, it.rect.offsetBy(0.0, 0.1)) })
            }
        val page = PageText(lines)
        expect(page.blocks.size == 2)
        expect(page.blocks[1].text == "Next paragraph")
    }

    @Test fun rawLinesRoundTripThroughJSON() {
        val page = PageText(makeLines(listOf("The aero-", "dynamic force")))
        val serializer = ListSerializer(RawLine.serializer())
        val data = Json.encodeToString(serializer, page.rawLines)
        val restored = PageText(Json.decodeFromString(serializer, data))
        expect(restored.rawLines == page.rawLines)
        expect(restored.blocks == page.blocks)
    }
}
